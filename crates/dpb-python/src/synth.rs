/// Base synthetic data generator
#[pyclass(name = "SyntheticGenerator", subclass)]
pub struct PySyntheticGenerator {
    name: String,
    config: HashMap<String, f64>,
}

#[pymethods]
impl PySyntheticGenerator {
    #[new]
    #[pyo3(signature = (name="base", config=None))]
    fn new(name: &str, config: Option<HashMap<String, f64>>) -> Self {
        Self {
            name: name.to_string(),
            config: config.unwrap_or_default(),
        }
    }

    /// Generate synthetic signal data
    ///
    /// Args:
    ///     duration (float): Duration in seconds
    ///     sample_rate (float): Sampling rate in Hz
    ///     seed (int): Random seed for reproducibility
    ///
    /// Returns:
    ///     tuple: (TimeSeries, GroundTruth)
    fn generate(
        &self,
        duration: f64,
        sample_rate: f64,
        _seed: Option<u64>,
        py: Python,
    ) -> PyResult<(PyTimeSeries, PyGroundTruth)> {
        // Base implementation - override in subclasses
        let num_samples = (duration * sample_rate) as usize;
        let data = PyArray2::<f32>::zeros(py, (num_samples, 1), false);
        let signal = PyTimeSeries::new(data.into(), sample_rate, 0.0);
        let ground_truth = PyGroundTruth::new(None, None, None);

        Ok((signal, ground_truth))
    }

    #[getter]
    fn name(&self) -> String {
        self.name.clone()
    }

    #[getter]
    fn config(&self) -> HashMap<String, f64> {
        self.config.clone()
    }

    fn __repr__(&self) -> String {
        format!("SyntheticGenerator(name='{}')", self.name)
    }
}

/// ECG synthetic data generator
///
/// Generates realistic synthetic ECG signals.
///
/// Args:
///     heart_rate (float): Mean heart rate in BPM
///     hrv_sdnn (float): Heart rate variability (SDNN in ms)
///     noise_level (float): Additive noise level
///     artifacts (bool): Include artifacts (baseline wander, etc.)
///
/// Example:
///     >>> gen = EcgGenerator(heart_rate=70, hrv_sdnn=50)
///     >>> signal, ground_truth = gen.generate(duration=60.0, sample_rate=250.0)
#[pyclass(name = "EcgGenerator", extends=PySyntheticGenerator)]
// Recorded from the Python-side constructor. The wrapper does not consume
// these yet, but dropping them would silently discard what a caller
// passed through the binding.
#[allow(dead_code)]
pub struct PyEcgGenerator {
    heart_rate: f64,
    hrv_sdnn: f64,
    noise_level: f64,
    artifacts: bool,
}

#[pymethods]
impl PyEcgGenerator {
    #[new]
    #[pyo3(signature = (heart_rate=70.0, hrv_sdnn=50.0, noise_level=0.05, artifacts=false))]
    fn new(
        heart_rate: f64,
        hrv_sdnn: f64,
        noise_level: f64,
        artifacts: bool,
    ) -> PyClassInitializer<Self> {
        let mut config = HashMap::new();
        config.insert("heart_rate".to_string(), heart_rate);
        config.insert("hrv_sdnn".to_string(), hrv_sdnn);
        config.insert("noise_level".to_string(), noise_level);

        PyClassInitializer::from(PySyntheticGenerator {
            name: "ECG".to_string(),
            config,
        })
        .add_subclass(Self {
            heart_rate,
            hrv_sdnn,
            noise_level,
            artifacts,
        })
    }

    #[pyo3(signature = (duration, sample_rate, seed=None))]
    fn generate(
        &self,
        duration: f64,
        sample_rate: f64,
        seed: Option<u64>,
        py: Python,
    ) -> PyResult<(PyTimeSeries, PyGroundTruth)> {
        // Generated by `dpb_synth::EcgMorphologyGenerator` rather than returned
        // as zeros. The R-peak times below are the generator's own event-level
        // ground truth, one per cardiac cycle.
        let params = EcgMorphologyParams {
            duration,
            sampling_rate: sample_rate,
            heart_rate: self.heart_rate,
            ..EcgMorphologyGenerator::default_params()
        };

        let generated = EcgMorphologyGenerator
            .generate(&params, seed.unwrap_or(0))
            .map_err(|e| {
                pyo3::exceptions::PyValueError::new_err(format!("ECG generation failed: {e}"))
            })?;

        let samples: Vec<f32> = generated.signal.iter().map(|&v| v as f32).collect();
        let num_samples = samples.len();
        let array = Array2::from_shape_vec((num_samples, 1), samples)
            .map_err(|e| pyo3::exceptions::PyValueError::new_err(format!("signal shape: {e}")))?;
        let data = PyArray2::from_owned_array(py, array);
        let signal = PyTimeSeries::new(data.into(), sample_rate, 0.0);

        let timestamps: Vec<f64> = generated
            .ground_truth
            .events
            .iter()
            .map(|e| e.time)
            .collect();

        let mut ground_truth = PyGroundTruth::new(None, Some(timestamps), None);
        ground_truth.add_label("modality".to_string(), "ecg".to_string());
        ground_truth.add_label("heart_rate".to_string(), self.heart_rate.to_string());
        ground_truth.add_label("events".to_string(), "R_peak".to_string());

        Ok((signal, ground_truth))
    }

    #[getter]
    fn heart_rate(&self) -> f64 {
        self.heart_rate
    }

    #[setter]
    fn set_heart_rate(&mut self, value: f64) {
        self.heart_rate = value;
    }
}

