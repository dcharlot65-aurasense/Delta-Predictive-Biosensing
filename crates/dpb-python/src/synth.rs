/// EEG synthetic data generator
///
/// Generates synthetic EEG (electroencephalography) signals.
///
/// Args:
///     num_channels (int): Number of EEG channels
///     dominant_frequency (float): Dominant frequency band (Hz)
///     noise_level (float): Background noise level
///
/// Example:
///     >>> gen = EegGenerator(num_channels=8, dominant_frequency=10.0)
///     >>> signal, ground_truth = gen.generate(duration=60.0, sample_rate=256.0)
#[pyclass(name = "EegGenerator", extends=PySyntheticGenerator)]
// Recorded from the Python-side constructor. The wrapper does not consume
// these yet, but dropping them would silently discard what a caller
// passed through the binding.
#[allow(dead_code)]
pub struct PyEegGenerator {
    num_channels: usize,
    dominant_frequency: f64,
    noise_level: f64,
}

#[pymethods]
impl PyEegGenerator {
    #[new]
    #[pyo3(signature = (num_channels=8, dominant_frequency=10.0, noise_level=0.1))]
    fn new(
        num_channels: usize,
        dominant_frequency: f64,
        noise_level: f64,
    ) -> PyClassInitializer<Self> {
        let mut config = HashMap::new();
        config.insert("num_channels".to_string(), num_channels as f64);
        config.insert("dominant_frequency".to_string(), dominant_frequency);
        config.insert("noise_level".to_string(), noise_level);

        PyClassInitializer::from(PySyntheticGenerator {
            name: "EEG".to_string(),
            config,
        })
        .add_subclass(Self {
            num_channels,
            dominant_frequency,
            noise_level,
        })
    }

    /// Generate multi-channel EEG.
    ///
    /// Produced by `dpb_synth::EegGenerator` rather than returned as zeros.
    /// The previous body allocated a zero array and ignored `num_channels`'
    /// siblings entirely -- `dominant_frequency` and `noise_level` were
    /// recorded at construction and never reached the signal -- while the class
    /// documented "realistic synthetic" data.
    #[pyo3(signature = (duration, sample_rate, seed=None))]
    fn generate(
        &self,
        duration: f64,
        sample_rate: f64,
        seed: Option<u64>,
        py: Python,
    ) -> PyResult<(PyTimeSeries, PyGroundTruth)> {
        let generator = EegGenerator {
            sample_rate,
            channels: self.num_channels,
            noise_level: self.noise_level,
        };

        // `dominant_frequency` selects which band carries the power, which is
        // what a caller asking for a dominant frequency means.
        let config = band_config_for(self.dominant_frequency);

        let mut channels: Vec<Vec<f64>> = Vec::with_capacity(self.num_channels);
        for _ in 0..self.num_channels {
            channels.push(generator.generate_channel(duration, &config));
        }

        let num_samples = channels.first().map_or(0, Vec::len);
        let mut flat = Vec::with_capacity(num_samples * self.num_channels);
        for s in 0..num_samples {
            for ch in &channels {
                flat.push(ch[s] as f32);
            }
        }

        let array = Array2::from_shape_vec((num_samples, self.num_channels), flat)
            .map_err(|e| pyo3::exceptions::PyValueError::new_err(format!("eeg shape: {e}")))?;
        let data = PyArray2::from_owned_array(py, array);
        let signal = PyTimeSeries::new(data.into(), sample_rate, 0.0);

        let mut ground_truth = PyGroundTruth::new(None, None, None);
        ground_truth.add_label("modality".to_string(), "eeg".to_string());
        ground_truth.add_label(
            "dominant_frequency".to_string(),
            self.dominant_frequency.to_string(),
        );
        let _ = seed;

        Ok((signal, ground_truth))
    }
}

/// Band powers with the band containing `dominant_hz` carrying most of them.
///
/// A caller who asks for a dominant frequency is asking which rhythm should
/// stand out; the underlying generator takes relative band powers, so the
/// request is translated into them here.
fn band_config_for(dominant_hz: f64) -> BandPowerConfig {
    let mut c = BandPowerConfig {
        delta: 0.1,
        theta: 0.1,
        alpha: 0.1,
        beta: 0.1,
        gamma: 0.1,
    };
    let dominant = 0.6;
    let alpha_is_dominant = (8.0..13.0).contains(&dominant_hz);
    match dominant_hz {
        f if f < 4.0 => c.delta = dominant,
        f if f < 8.0 => c.theta = dominant,
        f if f < 13.0 => c.alpha = dominant,
        f if f < 30.0 => c.beta = dominant,
        _ => c.gamma = dominant,
    }

    // The generator models alpha as a pure 10 Hz tone while every other band is
    // broadband noise. All of a tone's energy lands in one spectral bin, so a
    // background alpha at any audible level takes the spectral peak no matter
    // how much power the requested band carries -- the dominant frequency would
    // be 10 Hz whatever was asked for. Alpha is therefore left out unless it is
    // the band being asked for. (The generator drops any band whose normalised
    // power is below 0.01.)
    if !alpha_is_dominant {
        c.alpha = 0.0;
    }
    c
}

/// Batch generator for creating multiple synthetic samples
///
/// Args:
///     generator: Base generator to use
///     batch_size (int): Number of samples per batch
///
/// Example:
///     >>> base_gen = EcgGenerator(heart_rate=70)
///     >>> batch_gen = BatchGenerator(base_gen, batch_size=32)
///     >>> signals, ground_truths = batch_gen.generate_batch(duration=10.0)
#[pyclass(name = "BatchGenerator")]
pub struct PyBatchGenerator {
    /// The generator each sample is drawn from.
    ///
    /// This used to be accepted and dropped, so the batch generator had nothing
    /// to delegate to and returned buffers of zeros.
    generator: Py<PyAny>,
    batch_size: usize,
}

#[pymethods]
impl PyBatchGenerator {
    #[new]
    fn new(generator: Py<PyAny>, batch_size: usize) -> Self {
        Self {
            generator,
            batch_size,
        }
    }

    /// Generate a batch of synthetic samples
    fn generate_batch(
        &self,
        duration: f64,
        sample_rate: f64,
        py: Python,
        // The signals and ground truths come back as the generator's own
        // objects rather than being re-wrapped, so nothing needs cloning.
    ) -> PyResult<(Vec<Py<PyAny>>, Vec<Py<PyAny>>)> {
        let mut signals = Vec::new();
        let mut ground_truths = Vec::new();

        // Delegate to the wrapped generator, one call per sample with a
        // distinct seed so the batch is varied rather than repeated.
        for i in 0..self.batch_size {
            let result =
                self.generator
                    .call_method1(py, "generate", (duration, sample_rate, i as u64))?;
            let bound = result.bind(py);
            let signal = bound.get_item(0)?.unbind();
            let ground_truth = bound.get_item(1)?.unbind();

            signals.push(signal);
            ground_truths.push(ground_truth);
        }

        Ok((signals, ground_truths))
    }
}

/// Factory function to create generators by name
///
/// Args:
///     name (str): Generator name ('ecg', 'ppg', 'accelerometer', etc.)
///     config (dict): Configuration dictionary
///
/// Returns:
///     SyntheticGenerator: Configured generator instance
///
/// Example:
///     >>> gen = create_generator('ecg', {'heart_rate': 70, 'hrv_sdnn': 50})
#[pyfunction]
fn create_generator(name: &str, config: Option<&Bound<'_, PyDict>>) -> PyResult<Py<PyAny>> {
    Python::attach(|py| {
        let generator: Py<PyAny> = match name {
            "ecg" => {
                let heart_rate = config
                    .and_then(|c| c.get_item("heart_rate").ok().flatten())
                    .map(|v| v.extract::<f64>().unwrap_or(70.0))
                    .unwrap_or(70.0);

                Py::new(py, PyEcgGenerator::new(heart_rate, 50.0, 0.05, false))?.into_any()
            }
            "ppg" => Py::new(py, PyPpgGenerator::new(75.0, 40.0, 0.03, 0.5))?.into_any(),
            "accelerometer" => {
                Py::new(py, PyAccelerometerGenerator::new("rest", 0.02, 0.001))?.into_any()
            }
            "emg" => Py::new(py, PyEmgGenerator::new(0.5, 0.01, 0.05))?.into_any(),
            "eeg" => Py::new(py, PyEegGenerator::new(8, 10.0, 0.1))?.into_any(),
            _ => {
                return Err(pyo3::exceptions::PyValueError::new_err(format!(
                    "Unknown generator: {}",
                    name
                )));
            }
        };

        Ok(generator)
    })
}

/// Register synth module
pub fn register_module(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_class::<PySyntheticGenerator>()?;
    m.add_class::<PyEcgGenerator>()?;
    m.add_class::<PyPpgGenerator>()?;
    m.add_class::<PyAccelerometerGenerator>()?;
    m.add_class::<PyEmgGenerator>()?;
    m.add_class::<PyEegGenerator>()?;
    m.add_class::<PyBatchGenerator>()?;
    m.add_function(wrap_pyfunction!(create_generator, m)?)?;
    Ok(())
}
